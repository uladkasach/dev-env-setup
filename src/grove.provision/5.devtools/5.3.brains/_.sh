  if [[ -z "$unjudged" ]]; then
    return 0
  fi
  if ! total="$(_grove_provision_5_3_brains_census_total <<< "$unjudged")"; then
    echo "   ✋ $real holds hooks by an author outside \`repo=…\`, and the census could not total them" >&2
